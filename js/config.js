(function setupPreloader(){
  function init(){
    const pre = document.getElementById("preloader");
    if (!pre || pre.dataset.upgraded) return;
    pre.dataset.upgraded = "1";
    pre.innerHTML =
      '<img class="preloader-logo" src="https://fontmeme.com/permalink/251118/641e420a0d47cd6fde155dd167a7614b.png" alt="Turgot+">' +
      '<div class="preloader-bar"><div class="preloader-bar-fill"></div></div>' +
      '<div class="preloader-pct">0%</div>';

    const fill = pre.querySelector(".preloader-bar-fill");
    const pct  = pre.querySelector(".preloader-pct");
    let v = 0, done = false;
    const tick = () => {
      if (done) return;
      const target = document.readyState === "complete" ? 92 : 88;
      if (v < target) v += Math.max(0.6, (target - v) * 0.04);
      const shown = Math.min(99, Math.round(v));
      fill.style.width = shown + "%";
      pct.textContent  = shown + "%";
      requestAnimationFrame(tick);
    };
    requestAnimationFrame(tick);

    pre._finish = () => {
      done = true;
      fill.style.width = "100%";
      pct.textContent  = "100%";
      setTimeout(() => {
        pre.classList.add("fade-out");
        setTimeout(() => { pre.style.display = "none"; }, 380);
      }, 180);
    };
  }
  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", init);
  } else { init(); }

  window.addEventListener("load", () => {
    if (window.stopAutoPreloader) return; // page spéciale (ex: video.html)
    const pre = document.getElementById("preloader");
    if (!pre) return;
    if (pre._finish) pre._finish(); else pre.style.display = "none";
  });
})();

