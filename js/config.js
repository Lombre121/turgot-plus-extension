export function injectNav(activePage, session) {
  const nav = document.getElementById('main-nav');
  if (!nav) return;

  const pages = [
    { href:'index.html',     label:'Accueil',   key:'accueil'   },
    { href:'recherche.html', label:'Recherche', key:'recherche' },
    { href:'series.html',    label:'Séries',    key:'series'    },
    { href:'film.html',      label:'Films',     key:'films'     },
    { href:'ma-liste.html',  label:'Ma liste',  key:'liste'     },
  ];

  const links = pages.map(p =>
    `<a href="${p.href}" class="nav-link${activePage===p.key?' active':''}">${p.label}</a>`
  ).join('');

  const username = session?.user?.user_metadata?.username || session?.user?.email?.split('@')[0] || '';

  const userBlock = session
    ? `<div class="nav-user">
         <a href="profil.html" class="nav-username">${username}</a>
         <button onclick="window.__signOut()" class="nav-logout-btn">${ICONS.logout} Déconnexion</button>
       </div>`
    : `<a href="connexion.html" class="nav-link${activePage==='connexion'?' active':''}">Connexion</a>`;

  nav.innerHTML = `
    <a href="index.html">
      <img src="https://fontmeme.com/permalink/251118/641e420a0d47cd6fde155dd167a7614b.png" class="nav-logo" alt="Turgot+">
    </a>
    <button id="hamburger-btn" aria-label="Menu">${ICONS.menu}</button>
    <div id="nav-menu" class="nav-menu">
      ${links}
      ${userBlock}
    </div>`;

  document.getElementById('hamburger-btn').addEventListener('click', () =>
    document.getElementById('nav-menu').classList.toggle('open')
  );
}

export function createCard(item, type, watchlist, likes, sb, session) {
  const id    = String(item.id);
  const title = item.title || item.name || '';
  const year  = (item.release_date || item.first_air_date || '').substring(0, 4);
  const poster = item.poster_path;

  let inWl = watchlist.some(w => w.tmdb_id === id && w.media_type === type);
  let inLk = likes.some(l => l.tmdb_id === id && l.media_type === type);

  // 🔥 SEULE LIGNE MODIFIÉE
  const href = `details.html?id=${id}&type=${type}`;

  const card = document.createElement('a');
  card.className = 'card';
  card.href = href;
  card.innerHTML = `
    <img src="https://image.tmdb.org/t/p/w500${poster}" alt="${title}" loading="lazy">
    <div class="card-info">
      <h3>${title}</h3>
      <span>${year}</span>
    </div>
    <div class="card-actions">
      <button class="card-btn btn-wl ${inWl?'in-list':''}" title="${inWl?'Retirer':'Ajouter à ma liste'}">${inWl ? ICONS.check : ICONS.plus}</button>
      <button class="card-btn btn-lk ${inLk?'liked':''}" title="${inLk?'Retirer le like':'Aimer'}">${inLk ? ICONS.heart : ICONS.heartO}</button>
    </div>`;

  card.querySelector('.btn-wl').addEventListener('click', async e => {
    e.preventDefault(); e.stopPropagation();
    if (!session) { window.location.href = 'connexion.html'; return; }
    const btn = e.currentTarget;
    if (inWl) {
      await sb.from('watchlist').delete().eq('user_id',session.user.id).eq('tmdb_id',id).eq('media_type',type);
      watchlist.splice(watchlist.findIndex(w=>w.tmdb_id===id&&w.media_type===type),1);
      inWl = false; btn.innerHTML = ICONS.plus; btn.classList.remove('in-list'); btn.title='Ajouter à ma liste';
    } else {
      await sb.from('watchlist').upsert({user_id:session.user.id,tmdb_id:id,media_type:type,title,poster,watched:false,added_at:new Date().toISOString()});
      watchlist.push({tmdb_id:id,media_type:type});
      inWl = true; btn.innerHTML = ICONS.check; btn.classList.add('in-list'); btn.title='Retirer';
    }
  });

  card.querySelector('.btn-lk').addEventListener('click', async e => {
    e.preventDefault(); e.stopPropagation();
    if (!session) { window.location.href = 'connexion.html'; return; }
    const btn = e.currentTarget;
    if (inLk) {
      await sb.from('likes').delete().eq('user_id',session.user.id).eq('tmdb_id',id).eq('media_type',type);
      likes.splice(likes.findIndex(l=>l.tmdb_id===id&&l.media_type===type),1);
      inLk = false; btn.innerHTML = ICONS.heartO; btn.classList.remove('liked'); btn.title='Aimer';
    } else {
      await sb.from('likes').upsert({user_id:session.user.id,tmdb_id:id,media_type:type,title,poster,liked_at:new Date().toISOString()});
      likes.push({tmdb_id:id,media_type:type});
      inLk = true; btn.innerHTML = ICONS.heart; btn.classList.add('liked'); btn.title='Retirer le like';
    }
  });

  return card;
}

